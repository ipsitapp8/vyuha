/**
 * Security headers for the nginx web container, generated at build time from the same VITE_* values
 * the bundle is compiled with, so the Content-Security-Policy allows exactly the API and map hosts this
 * build talks to (vite.config.ts emits the result; apps/web/Dockerfile installs it).
 */
export interface SecurityHeaderInputs {
  /** VITE_API_URL: absolute (another origin, e.g. http://localhost:4000) or a same-origin path. */
  apiUrl: string | undefined;
  /** VITE_MAP_MODE: 'online' loads the hosted map style and tiles; anything else is offline. */
  mapMode: string | undefined;
  /** VITE_MAP_STYLE_URL: the hosted style (online mode only). */
  mapStyleUrl: string | undefined;
}

/** The API default the app itself uses when VITE_API_URL is unset (lib/api.ts, useSessionSocket). */
const DEFAULT_API_URL = 'http://localhost:4000';

/** http(s) origin of an absolute URL; null for a relative path (same origin) or anything else. */
function httpOrigin(raw: string | undefined): string | null {
  if (!raw) return null;
  try {
    const url = new URL(raw);
    return url.protocol === 'http:' || url.protocol === 'https:' ? url.origin : null;
  } catch {
    return null;
  }
}

/** connect-src: this origin, the API and its live socket, and the hosted map in online mode. */
export function connectSources(inputs: SecurityHeaderInputs): string[] {
  const out = new Set<string>(["'self'"]);
  const api = httpOrigin(inputs.apiUrl ?? DEFAULT_API_URL);
  if (api) {
    out.add(api);
    out.add(api.replace(/^http/, 'ws')); // Socket.IO upgrades to ws:// or wss:// on the API origin
  }
  if (inputs.mapMode === 'online') {
    const map = httpOrigin(inputs.mapStyleUrl);
    if (map) out.add(map);
  }
  return [...out];
}

export function contentSecurityPolicy(inputs: SecurityHeaderInputs): string {
  return [
    "default-src 'self'",
    "script-src 'self'",
    // Inline style attributes come from React, MapLibre and Recharts; scripts stay strictly 'self'.
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob:",
    "font-src 'self' data:",
    `connect-src ${connectSources(inputs).join(' ')}`,
    // MapLibre's module worker is served from /maplibre/; it may also spawn blob: workers.
    "worker-src 'self' blob:",
    "media-src 'self' blob: data:",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
  ].join('; ');
}

/**
 * nginx `add_header` lines. Included at server level and again in every location that sets its own
 * headers (nginx drops inherited add_header lines in such a location). `$vyuha_hsts` is defined by a
 * `map` in nginx.conf: HSTS only when a TLS-terminating proxy says the request came over https.
 */
export function nginxSecurityHeaders(inputs: SecurityHeaderInputs): string {
  const lines = [
    `add_header Content-Security-Policy "${contentSecurityPolicy(inputs)}" always;`,
    'add_header X-Content-Type-Options nosniff always;',
    'add_header X-Frame-Options DENY always;',
    'add_header Referrer-Policy no-referrer always;',
    'add_header Permissions-Policy "camera=(), microphone=(), geolocation=(), payment=(), usb=()" always;',
    'add_header Cross-Origin-Opener-Policy same-origin always;',
    'add_header Strict-Transport-Security $vyuha_hsts always;',
  ];
  return `# Generated by apps/web/vite.config.ts at build time. Do not edit.\n${lines.join('\n')}\n`;
}
